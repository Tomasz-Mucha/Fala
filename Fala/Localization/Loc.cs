    public string Get(string key)
    {
        var table = Table(Language);
        if (table.TryGetValue(key, out var s))
            return s;
        if (Pl.TryGetValue(key, out var fallback))
            return fallback;
        return key;
    }

    public string Format(string key, params object[] args)
        => string.Format(Culture, ApplyPlurals(Get(key), args), args);

    // Znacznik {n:P:forma1|forma2|forma3} wybiera odmianę słowa według liczby z argumentu n.
    // Polski: 1 podcast · 2–4 podcasty (bez 12–14) · 5+ podcastów; szwedzki i angielski: 1 / reszta.
    private static readonly System.Text.RegularExpressions.Regex PluralToken =
        new(@"\{(\d+):P:([^}]*)\}", System.Text.RegularExpressions.RegexOptions.Compiled);

    private string ApplyPlurals(string text, object[] args)
    {
        if (!text.Contains(":P:", StringComparison.Ordinal))
            return text;
        return PluralToken.Replace(text, m =>
        {
            var index = int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture);
            var forms = m.Groups[2].Value.Split('|');
            var n = index < args.Length ? Convert.ToInt64(args[index], CultureInfo.InvariantCulture) : 0;
            var form = PluralForm(Language, n, forms.Length);
            // Nawiasy klamrowe w wybranej formie nie mogą trafić do string.Format.
            return forms[form].Replace("{", "{{").Replace("}", "}}");
        });
    }

    internal static int PluralForm(string language, long n, int formCount)
    {
        n = Math.Abs(n);
        if (language == "pl" && formCount >= 3)
        {
            if (n == 1) return 0;
            var d = n % 10;
            var dd = n % 100;
            return d is >= 2 and <= 4 && dd is < 12 or > 14 ? 1 : 2;
        }
        return n == 1 ? 0 : Math.Min(1, formCount - 1);
    }

    public void SetLanguage(string code)
    {
        Language = code is "sv" or "en" ? code : "pl";
        var culture = Culture = Language switch
        {
            "sv" => new CultureInfo("sv-SE"),
            "en" => new CultureInfo("en-US"),
            _ => new CultureInfo("pl-PL")
        };
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        PropertyChanged?.Invoke(this, new System.ComponentModel.PropertyChangedEventArgs(null));
        Changed?.Invoke();
    }

